"""Structured battle records.

Built on a property we verified rather than assumed: a seeded battle replays
exactly. So a trajectory stores the *inputs* -- format, seed, packed teams, and
the ordered decisions -- rather than a snapshot of every state. That is far
smaller, and it cannot drift out of internal consistency the way a parallel
copy of derived state can.

Observations are therefore not stored: they are regenerated by replaying, which
also means training data is always produced by the *current* observation code
rather than whatever version happened to record it. `git_commit` is captured so
a replay that no longer reproduces the recorded result is detectable.
"""

import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Annotated

from pydantic import BaseModel, Field

from champions_ai.domain import JointAction, TeamPreviewAction

SCHEMA_VERSION = 1

RecordedAction = Annotated[JointAction | TeamPreviewAction, Field(discriminator="kind")]


class DecisionRecord(BaseModel, frozen=True):
    """One player's choice at one decision point."""

    turn: int
    player: int
    action: RecordedAction
    # How many options the agent was choosing between. Cheap to record and
    # needed to interpret a choice -- picking one action out of two is not the
    # same evidence as picking it out of ninety.
    legal_action_count: int | None = None


class Trajectory(BaseModel, frozen=True):
    """A complete battle, stored as what it takes to reproduce it."""

    schema_version: int = SCHEMA_VERSION
    format_id: str
    seed: str | None
    packed_teams: tuple[str, str]
    decisions: tuple[DecisionRecord, ...]
    winner: int | None
    turns: int
    recorded_at: str
    git_commit: str | None = None
    metadata: dict[str, str] = Field(default_factory=dict)
    # Kept optional: useful for debugging a specific battle, redundant with the
    # seed for reproduction, and by far the largest part of the record.
    protocol: tuple[str, ...] = ()

    @property
    def replayable(self) -> bool:
        """Whether this record can reproduce its battle exactly."""
        return self.seed is not None

    def without_protocol(self) -> "Trajectory":
        return self.model_copy(update={"protocol": ()})

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.model_dump_json(indent=2), encoding="utf-8")

    @classmethod
    def load(cls, path: Path) -> "Trajectory":
        return cls.model_validate_json(path.read_text(encoding="utf-8"))


def git_commit() -> str | None:
    """Current commit, or None outside a repository. Never raises."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=5,
            check=True,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return result.stdout.strip() or None


def utc_now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")
